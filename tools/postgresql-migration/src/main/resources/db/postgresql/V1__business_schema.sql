-- PostgreSQL18.6 target schema only. No data rewrite or source/target adoption.
-- Identifier/name comparison is explicit; this is not a claim of complete MySQL collation equivalence.
CREATE COLLATION pubburi_ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);
CREATE TABLE t_user (
    id VARCHAR(100) COLLATE pubburi_ci PRIMARY KEY,
    name VARCHAR(100) COLLATE pubburi_ci NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    auth_epoch UUID NOT NULL,
    stamps INT NOT NULL DEFAULT 0
);

CREATE TABLE t_product (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) COLLATE pubburi_ci NOT NULL,
    type VARCHAR(20) COLLATE pubburi_ci NOT NULL,
    price INT NOT NULL,
    img VARCHAR(100) NOT NULL,
    abv REAL NOT NULL,
    order_count INT NOT NULL DEFAULT 0
);

CREATE TABLE t_product_feature (
    product_id INT PRIMARY KEY,
    volume_ml INT NULL,
    description VARCHAR(2000) NULL,
    taste_known BOOLEAN NOT NULL DEFAULT FALSE,
    aroma_known BOOLEAN NOT NULL DEFAULT FALSE,
    source_name VARCHAR(200) NULL,
    source_url VARCHAR(1000) NULL,
    source_note VARCHAR(1000) NULL,
    CONSTRAINT ck_feature_volume CHECK (volume_ml IS NULL OR volume_ml BETWEEN 1 AND 1000000),
    CONSTRAINT ck_feature_source CHECK (
        (volume_ml IS NULL AND description IS NULL AND taste_known = FALSE AND aroma_known = FALSE)
        OR (source_name IS NOT NULL AND CHAR_LENGTH(TRIM(source_name)) > 0)
    ),
    CONSTRAINT fk_product_feature_product FOREIGN KEY (product_id)
        REFERENCES t_product(id) ON DELETE CASCADE
);

CREATE TABLE t_product_feature_tag (
    product_id INT NOT NULL,
    kind VARCHAR(5) NOT NULL,
    tag VARCHAR(40) COLLATE "C" NOT NULL,
    PRIMARY KEY (product_id, kind, tag),
    CONSTRAINT ck_feature_tag_kind CHECK (kind IN ('TASTE', 'AROMA')),
    CONSTRAINT ck_feature_tag_nonblank CHECK (CHAR_LENGTH(TRIM(tag)) > 0),
    CONSTRAINT fk_product_feature_tag FOREIGN KEY (product_id)
        REFERENCES t_product_feature(product_id) ON DELETE CASCADE
);

CREATE TABLE t_order (
    o_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(100) COLLATE pubburi_ci NULL,
    order_type VARCHAR(10) NOT NULL,
    order_table VARCHAR(20),
    order_time TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    completed CHAR(1) DEFAULT 'N',
    total_price INT DEFAULT NULL,
    price_basis VARCHAR(20) NOT NULL DEFAULT 'LEGACY_ESTIMATE',
    CONSTRAINT fk_order_history_user FOREIGN KEY (user_id) REFERENCES t_user(id) ON DELETE SET NULL
);

CREATE TABLE t_order_detail (
    d_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INT NOT NULL,
    product_id INT NULL,
    quantity INT NOT NULL DEFAULT 1,
    product_name VARCHAR(100) COLLATE pubburi_ci NOT NULL,
    product_type VARCHAR(20) COLLATE pubburi_ci NOT NULL,
    product_img VARCHAR(100) NOT NULL,
    unit_price INT NOT NULL,
    sum_price INT NOT NULL,
    CONSTRAINT fk_order_detail_order FOREIGN KEY (order_id) REFERENCES t_order(o_id) ON DELETE CASCADE,
    CONSTRAINT fk_order_history_product FOREIGN KEY (product_id) REFERENCES t_product(id) ON DELETE SET NULL
);

CREATE TABLE t_comment (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(100) COLLATE pubburi_ci NOT NULL,
    product_id INT NOT NULL,
    rating REAL NOT NULL DEFAULT 1,
    comment VARCHAR(200),
    CONSTRAINT fk_comment_user FOREIGN KEY (user_id) REFERENCES t_user(id) ON DELETE CASCADE,
    CONSTRAINT fk_comment_product FOREIGN KEY (product_id) REFERENCES t_product(id) ON DELETE CASCADE
);

CREATE TABLE t_stamp (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(100) COLLATE pubburi_ci NOT NULL,
    order_id INT NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    CONSTRAINT fk_stamp_user FOREIGN KEY (user_id) REFERENCES t_user(id) ON DELETE CASCADE,
    CONSTRAINT fk_stamp_order FOREIGN KEY (order_id) REFERENCES t_order(o_id) ON DELETE CASCADE
);

CREATE TABLE t_market (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL,
    img VARCHAR(200),
    name VARCHAR(100) COLLATE pubburi_ci NOT NULL
);

CREATE TABLE t_user_preference (
    user_id VARCHAR(100) COLLATE pubburi_ci PRIMARY KEY,
    survey_status VARCHAR(11) COLLATE "C" NOT NULL,
    categories_known BOOLEAN NOT NULL DEFAULT FALSE,
    taste_known BOOLEAN NOT NULL DEFAULT FALSE,
    aroma_known BOOLEAN NOT NULL DEFAULT FALSE,
    target_abv_percent DECIMAL(5,2) NULL,
    min_price_krw INT NULL,
    max_price_krw INT NULL,
    min_abv_percent DECIMAL(5,2) NULL,
    max_abv_percent DECIMAL(5,2) NULL,
    CONSTRAINT ck_preference_status CHECK (survey_status IN ('NOT_STARTED', 'SKIPPED', 'COMPLETED')),
    CONSTRAINT ck_preference_target CHECK (target_abv_percent IS NULL OR target_abv_percent BETWEEN 0 AND 100),
    CONSTRAINT ck_preference_price CHECK ((min_price_krw IS NULL OR min_price_krw >= 0)
        AND (max_price_krw IS NULL OR max_price_krw >= 0)
        AND (min_price_krw IS NULL OR max_price_krw IS NULL OR min_price_krw <= max_price_krw)),
    CONSTRAINT ck_preference_abv CHECK ((min_abv_percent IS NULL OR min_abv_percent BETWEEN 0 AND 100)
        AND (max_abv_percent IS NULL OR max_abv_percent BETWEEN 0 AND 100)
        AND (min_abv_percent IS NULL OR max_abv_percent IS NULL OR min_abv_percent <= max_abv_percent)),
    CONSTRAINT ck_preference_skip CHECK (survey_status = 'COMPLETED' OR
        (categories_known = FALSE AND taste_known = FALSE AND aroma_known = FALSE
         AND target_abv_percent IS NULL AND min_price_krw IS NULL AND max_price_krw IS NULL
         AND min_abv_percent IS NULL AND max_abv_percent IS NULL)),
    CONSTRAINT fk_user_preference_user FOREIGN KEY (user_id) REFERENCES t_user(id) ON DELETE CASCADE
);

CREATE TABLE t_user_preference_value (
    user_id VARCHAR(100) COLLATE pubburi_ci NOT NULL,
    kind VARCHAR(8) COLLATE "C" NOT NULL,
    value_text VARCHAR(40) COLLATE "C" NOT NULL,
    PRIMARY KEY (user_id, kind, value_text),
    CONSTRAINT ck_preference_value_kind CHECK (kind IN ('CATEGORY', 'TASTE', 'AROMA')),
    CONSTRAINT ck_preference_value_nonblank CHECK (CHAR_LENGTH(TRIM(value_text)) > 0),
    CONSTRAINT fk_user_preference_value FOREIGN KEY (user_id) REFERENCES t_user_preference(user_id) ON DELETE CASCADE
);

CREATE TABLE t_user_favorite (
    user_id VARCHAR(100) COLLATE pubburi_ci NOT NULL,
    product_id INT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, product_id),
    CONSTRAINT fk_favorite_user FOREIGN KEY (user_id) REFERENCES t_user(id) ON DELETE CASCADE,
    CONSTRAINT fk_favorite_product FOREIGN KEY (product_id) REFERENCES t_product(id) ON DELETE CASCADE
);

CREATE TABLE t_product_search_version (
    product_id INT PRIMARY KEY,
    source_version BIGINT NOT NULL,
    CONSTRAINT ck_search_version_product CHECK (product_id > 0),
    CONSTRAINT ck_search_version_nonnegative CHECK (source_version >= 0)
);

CREATE TABLE t_product_search_outbox (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INT NOT NULL,
    source_version BIGINT NOT NULL,
    deleted BOOLEAN NOT NULL,
    payload JSON NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_search_product_version UNIQUE (product_id, source_version),
    CONSTRAINT ck_search_outbox_version CHECK (source_version > 0),
    CONSTRAINT fk_search_outbox_version FOREIGN KEY (product_id)
        REFERENCES t_product_search_version(product_id) ON DELETE RESTRICT
);

CREATE TABLE t_product_search_delivery (
    event_id BIGINT PRIMARY KEY,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING',
    claim_token UUID NULL,
    lease_until TIMESTAMP(6) WITH TIME ZONE NULL,
    available_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attempts INT NOT NULL DEFAULT 0,
    delivered_at TIMESTAMP(6) WITH TIME ZONE NULL,
    last_error VARCHAR(64) NULL,
    CONSTRAINT fk_search_delivery_event FOREIGN KEY (event_id)
        REFERENCES t_product_search_outbox(event_id) ON DELETE RESTRICT,
    CONSTRAINT ck_search_delivery_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_search_delivery_state CHECK (
        (status='PENDING' AND claim_token IS NULL AND lease_until IS NULL AND delivered_at IS NULL) OR
        (status='IN_FLIGHT' AND claim_token IS NOT NULL AND lease_until IS NOT NULL AND delivered_at IS NULL) OR
        (status='DELIVERED' AND claim_token IS NULL AND lease_until IS NULL AND delivered_at IS NOT NULL))
);

CREATE TABLE t_product_search_relay_target (
    singleton_id SMALLINT PRIMARY KEY,
    source_id UUID NOT NULL,
    fingerprint CHAR(64) COLLATE "C" NULL,
    identity_json JSON NULL,
    bound_at TIMESTAMP(6) WITH TIME ZONE NULL,
    CONSTRAINT ck_search_target_singleton CHECK (singleton_id=1),
    CONSTRAINT ck_search_target_binding CHECK (
        (fingerprint IS NULL AND identity_json IS NULL AND bound_at IS NULL) OR
        (fingerprint IS NOT NULL AND identity_json IS NOT NULL AND bound_at IS NOT NULL))
);

CREATE INDEX idx_favorite_user_created ON t_user_favorite (user_id, created_at, product_id);
CREATE INDEX idx_favorite_product ON t_user_favorite (product_id);
CREATE INDEX idx_search_delivery_pending ON t_product_search_delivery (status, available_at, event_id);
CREATE INDEX idx_search_delivery_lease ON t_product_search_delivery (status, lease_until ASC NULLS FIRST, event_id);
-- Preserve explicit source lookup indexes and MySQL's automatically created FK-supporting indexes.
CREATE INDEX idx_product_type ON t_product(type);
CREATE INDEX idx_product_order_count ON t_product(order_count);
CREATE INDEX idx_order_user_time ON t_order(user_id ASC NULLS FIRST, order_time ASC NULLS FIRST);
CREATE INDEX idx_order_detail_order ON t_order_detail(order_id);
CREATE INDEX idx_order_detail_product ON t_order_detail(product_id ASC NULLS FIRST);
CREATE INDEX fk_comment_user ON t_comment(user_id);
CREATE INDEX idx_comment_product ON t_comment(product_id);
CREATE INDEX fk_stamp_user ON t_stamp(user_id);
CREATE INDEX fk_stamp_order ON t_stamp(order_id);
